-- LoonInspect #848: run in a NEW disposable Snowflake account/schema first.
-- An account administrator runs this setup; LoonInspect never receives that role.
-- These names match the destination form defaults. CREATE intentionally refuses
-- an existing object: review it instead of replacing existing customer data.
USE ROLE ACCOUNTADMIN;
CREATE DATABASE LOONINSPECT;
CREATE ROLE LOON_WRITER;
CREATE ROLE LOON_ANALYST;
GRANT ROLE LOON_WRITER TO ROLE SYSADMIN;
GRANT ROLE LOON_ANALYST TO ROLE SYSADMIN;

CREATE TABLE LOONINSPECT.PUBLIC.LOON_EVENTS_RAW (
    SOURCE_ID VARCHAR NOT NULL,
    TENANT_ID VARCHAR NOT NULL,
    SOURCE_EVENT_KEY VARCHAR NOT NULL,
    EVENT_TYPE VARCHAR NOT NULL,
    OCCURRED_AT TIMESTAMP_TZ,
    QUEUED_AT TIMESTAMP_TZ,
    PAYLOAD VARIANT NOT NULL
) ROW_TIMESTAMP = TRUE;

CREATE PIPE LOONINSPECT.PUBLIC.LOON_EVENTS_PIPE AS
COPY INTO LOONINSPECT.PUBLIC.LOON_EVENTS_RAW
    (SOURCE_ID, TENANT_ID, SOURCE_EVENT_KEY, EVENT_TYPE, OCCURRED_AT, QUEUED_AT, PAYLOAD)
FROM (
    SELECT $1:SOURCE_ID::VARCHAR, $1:TENANT_ID::VARCHAR,
           $1:SOURCE_EVENT_KEY::VARCHAR, $1:EVENT_TYPE::VARCHAR,
           $1:OCCURRED_AT::TIMESTAMP_TZ, $1:QUEUED_AT::TIMESTAMP_TZ, $1:PAYLOAD
    FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
)
ON_ERROR = CONTINUE;

-- True server commit time: CURRENT_TIMESTAMP in a pipe can be its compile time.
-- The writer has INSERT only, so it cannot later change this row timestamp.
CREATE VIEW LOONINSPECT.PUBLIC.LOON_EVENTS AS
SELECT SOURCE_ID, TENANT_ID, SOURCE_EVENT_KEY, EVENT_TYPE, OCCURRED_AT, QUEUED_AT,
       METADATA$ROW_LAST_COMMIT_TIME AS LOADED_AT, PAYLOAD
FROM LOONINSPECT.PUBLIC.LOON_EVENTS_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY SOURCE_ID, TENANT_ID, SOURCE_EVENT_KEY
    ORDER BY METADATA$ROW_LAST_COMMIT_TIME ASC
) = 1;

-- Inventory snapshots are whole public events. Device IDs are only unique within
-- their source/tenant/connection. A missing source report date stays unknown.
CREATE VIEW LOONINSPECT.PUBLIC.LOON_MAC_OS_OBSERVATIONS AS
SELECT SOURCE_ID, TENANT_ID, SOURCE_EVENT_KEY,
       PAYLOAD:deviceMeta:connectionID::VARCHAR AS CONNECTION_ID,
       PAYLOAD:deviceMeta:jamfProID::VARCHAR AS DEVICE_ID,
       PAYLOAD:deviceMeta:hostName::VARCHAR AS HOST_NAME,
       TRY_TO_TIMESTAMP_TZ(PAYLOAD:deviceMeta:lastReportDate::VARCHAR) AS OBSERVED_AT,
       OCCURRED_AT AS EVENT_OCCURRED_AT, QUEUED_AT, LOADED_AT,
       PAYLOAD:operatingSystem:version::VARCHAR AS OS_VERSION,
       PAYLOAD:operatingSystem:build::VARCHAR AS OS_BUILD,
       COALESCE(TYPEOF(PAYLOAD:operatingSystem) = 'OBJECT', FALSE) AS OS_SECTION_OBSERVED,
       TRY_TO_TIMESTAMP_TZ(PAYLOAD:deviceMeta:lastReportDate::VARCHAR) IS NOT NULL
           AS OBSERVATION_DATE_KNOWN
FROM LOONINSPECT.PUBLIC.LOON_EVENTS
WHERE EVENT_TYPE = 'device.inventory';

-- Loading an older delayed observation never displaces newer dated evidence.
-- A device with only undated evidence is present with OBSERVATION_DATE_KNOWN=false.
CREATE VIEW LOONINSPECT.PUBLIC.LOON_MAC_OS_LATEST AS
SELECT * FROM LOONINSPECT.PUBLIC.LOON_MAC_OS_OBSERVATIONS
WHERE CONNECTION_ID IS NOT NULL AND DEVICE_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY SOURCE_ID, TENANT_ID, CONNECTION_ID, DEVICE_ID
    ORDER BY OBSERVED_AT DESC NULLS LAST, EVENT_OCCURRED_AT DESC NULLS LAST, SOURCE_EVENT_KEY
) = 1;

GRANT USAGE ON DATABASE LOONINSPECT TO ROLE LOON_WRITER;
