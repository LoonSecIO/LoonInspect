GRANT INSERT ON TABLE LOONINSPECT.PUBLIC.LOON_EVENTS_RAW TO ROLE LOON_WRITER;
GRANT OPERATE ON PIPE LOONINSPECT.PUBLIC.LOON_EVENTS_PIPE TO ROLE LOON_WRITER;
CREATE USER LOON_WRITER TYPE = SERVICE DEFAULT_ROLE = LOON_WRITER;
GRANT ROLE LOON_WRITER TO USER LOON_WRITER;
